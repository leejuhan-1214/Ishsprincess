import type { CharacterId, Effect, Line, LocationId, Scene } from '../types';

type Branch = [text: string, response: string, extra?: Effect[]];
const globalEffect = (stat: 'harmony' | 'fair' | 'reputation' | 'ethics' | 'safety', amount: number): Effect => ({ target: 'global', stat, amount });

function dialogue(hero: CharacterId, script: string): Line[] {
  const speakers: Record<string, Line['speaker']> = { A: hero, P: 'player', N: 'narrator', T: 'teacher', S: 'student', W: 'world' };
  return script.trim().split('\n').map((raw) => {
    const separator = raw.indexOf('|');
    return { speaker: speakers[raw.slice(0, separator)] ?? 'narrator', text: raw.slice(separator + 1).trim() };
  });
}

function makeScene(hero: CharacterId, chapter: number, title: string, location: LocationId, script: string, branches: [Branch, Branch, Branch]): Scene {
  const labels = ['good', 'neutral', 'bad'];
  const risingSpecial = hero !== 'taewoo';
  return {
    id: `${hero}-${chapter}`, title, location, day: 1 - chapter,
    lines: dialogue(hero, script),
    choices: branches.map(([text, response, extra = []], index) => ({
      id: `${hero}-${chapter}-${labels[index]}`, text, response: dialogue(hero, response),
      effects: [
        { target: hero, stat: 'affection', amount: [8, 6, -4][index] },
        { target: hero, stat: 'trust', amount: [10, 4, -8][index] },
        { target: hero, stat: 'jealousy', amount: [-4, 0, 5][index] },
        { target: hero, stat: 'special', amount: (risingSpecial ? 1 : -1) * [8, 2, -8][index] },
        ...extra,
      ],
      flags: index === 0 ? [`${hero}-key-${chapter}`] : index === 2 ? [`${hero}-hurt-${chapter}`] : [],
    })),
  };
}

