/** Scores alone never imply that a classmate has agreed to a relationship. */
export function routeProgress(s:RState,person:RHero):RouteProgress{
 const prefix=`route:${person}:`;
 // Re-evaluate the actual saved choice, never invent a memory from affection
 // or the number of completed minigames. No migration writes/reset are needed.
 const legacy=s.flags.flatMap(flag=>{
  const match=new RegExp(`^memory:hangout-${person}-([1-5]):(followup:)?([0-2])$`).exec(flag);
  if(!match)return [];
  const visit=match[2]?2:1;
  return s.flags.includes(`read:hangout-${person}-${match[1]}-v${visit}`)?routeChoiceFlags(person,Number(match[1])-1,visit,Number(match[3])):[];
 });
 const flags=[...s.flags,...legacy];
 const memories=flags.flatMap(flag=>{
  if(!flag.startsWith(prefix))return [];
  const match=/^([1-5]):([a-z][a-z-]+)$/.exec(flag.slice(prefix.length));
  return match?[{chapter:Number(match[1]),key:match[2]}]:[];
 });
 const chapters=[...new Set(memories.map(item=>item.chapter))].sort();
 const keys=[...new Set(memories.map(item=>item.key))];
 const early=chapters.some(chapter=>chapter<=2),late=chapters.some(chapter=>chapter>=3);
 const committed=flags.includes(`${prefix}commitment`);
 const eligible=s.focus===person&&early&&late&&chapters.length>=3&&keys.length>=3&&committed&&s.bonds[person].affection>=64&&s.bonds[person].trust>=60;
 return{chapters,memories:keys,committed,early,late,eligible};
}
export const heroineRomanceEligible=(s:RState,person:RHero):boolean=>routeProgress(s,person).eligible;

